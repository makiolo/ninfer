int run_case(std::size_t index) {
    const Case& c = cases()[index];
    std::vector<int> positions(static_cast<std::size_t>(c.axes) * kTokens);
    for (int a = 0; a < c.axes; ++a)
        for (int t = 0; t < kTokens; ++t) positions[a * kTokens + t] = c.first_position + 97 * a + (2 * a + 1) * t;

    std::uint32_t state = 4001u + static_cast<std::uint32_t>(index);
    std::vector<std::uint16_t> x(static_cast<std::size_t>(kHeadDim) * kHeads * kTokens);
    for (auto& word : x) {
        state = state * 1664525u + 1013904223u;
        word = f32_to_bf16(static_cast<float>((static_cast<double>(state >> 8) / 8388608.0 - 1.0) * 4.0));
    }

    GuardedDeviceBuffer device_x(x.size() * 2), device_pos(positions.size() * sizeof(int));
    device_x.copy_from_host(x.data(), device_x.bytes());
    device_pos.copy_from_host(positions.data(), device_pos.bytes());
    Tensor position_tensor(device_pos.span(), DType::I32, {kTokens, c.axes});
    Tensor x_tensor(device_x.span(), DType::BF16, {kHeadDim, kHeads, kTokens});
    ops::rope(position_tensor, kRotary, kTheta, x_tensor, cuda_environment().default_execution);
    cuda_synchronize();
    const auto got = from_device<std::uint16_t>(device_x.data(), x.size());

    const std::string label = "rope large position axes=" + std::to_string(c.axes) + " pos0=" + std::to_string(c.first_position);
    int violations = 0, passthrough = 0;
    double worst = 0.0;
    for (int t = 0; t < kTokens; ++t)
        for (int h = 0; h < kHeads; ++h) {
            const std::size_t base = (static_cast<std::size_t>(t) * kHeads + h) * kHeadDim;
            for (int i = 0; i < kHalf; ++i) {
                const double cs = c.cos_sin[(static_cast<std::size_t>(t) * kHalf + i) * 2];
                const double sn = c.cos_sin[(static_cast<std::size_t>(t) * kHalf + i) * 2 + 1];
                const double a = bf16_to_f32(x[base + i]), b = bf16_to_f32(x[base + i + kHalf]);
                const double norm = std::hypot(a, b);
                const double want_lo = a * cs - b * sn, want_hi = b * cs + a * sn;
                const double err_lo = std::abs(static_cast<double>(bf16_to_f32(got[base + i])) - want_lo);
                const double err_hi = std::abs(static_cast<double>(bf16_to_f32(got[base + i + kHalf])) - want_hi);
                worst = std::max({worst, norm == 0.0 ? 0.0 : std::max(err_lo, err_hi) / norm});
                if (!(err_lo <= kPairRtol * norm) || !(err_hi <= kPairRtol * norm)) ++violations;
            }
            for (int d = kRotary; d < kHeadDim; ++d)
                if (got[base + d] != x[base + d]) ++passthrough;
        }
    if (violations != 0)
        std::cerr << label << ": " << violations << " pairs exceed " << kPairRtol << " of pair norm (worst " << worst << ")\n";
    if (passthrough != 0) std::cerr << label << ": " << passthrough << " non-rotary values changed\n";
    int failures = (violations != 0) + (passthrough != 0);
    failures += verify_exact((label + " positions").c_str(), from_device<int>(device_pos.data(), positions.size()), positions);
    failures += device_x.verify_guards((label + " x guards").c_str()) + device_pos.verify_guards((label + " position guards").c_str());
    return failures;
}

