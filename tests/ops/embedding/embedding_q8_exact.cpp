std::size_t align_up(std::size_t v, std::size_t a) { return (v + a - 1) / a * a; }
int code_of(int row, int group, int lane) { return ((lane + 32 * (group / 10) + 37 * row) & 255) - 128; }
int scale_of(int row, int group) { return (group + row) % kScales; }
std::uint16_t norm_zero(std::uint16_t w) { return w == 0x8000 ? std::uint16_t{0} : w; }

int run_case(int d, int tokens, std::size_t output_offset) {
    const int groups = d / kGroup;
    const std::size_t code_bytes = static_cast<std::size_t>(kRows) * d, scale_offset = align_up(code_bytes, 256);
    GuardedDeviceBuffer payload(scale_offset + static_cast<std::size_t>(kRows) * groups * 2);
    std::vector<std::uint8_t> host(payload.bytes(), 0);
    for (int r = 0; r < kRows; ++r)
        for (int g = 0; g < groups; ++g) {
            const std::uint16_t s = kScaleWords[scale_of(r, g)];
            host[scale_offset + (static_cast<std::size_t>(r) * groups + g) * 2]     = s & 0xff;
            host[scale_offset + (static_cast<std::size_t>(r) * groups + g) * 2 + 1] = s >> 8;
            for (int l = 0; l < kGroup; ++l)
                host[static_cast<std::size_t>(r) * d + g * kGroup + l] = static_cast<std::uint8_t>(code_of(r, g, l));
        }
    payload.copy_from_host(host.data(), host.size());

    auto* base = static_cast<std::uint8_t*>(payload.data());
    Weight weight{};
    weight.qtype = QType::Q8_G32_FP16;
    weight.layout = QuantLayout::RowSplit;
    weight.scale_dtype = DType::FP16;
    weight.device = payload.device();
    weight.payload = base;
    weight.payload_bytes = payload.bytes();
    weight.qdata = base;
    weight.qhigh = nullptr;
    weight.scales = base + scale_offset;
    weight.high_plane_bytes = 0;
    weight.group_size = weight.group = kGroup;
    weight.ndim = 2;
    weight.shape[0] = weight.padded_shape[0] = weight.n = kRows;
    weight.shape[1] = weight.padded_shape[1] = weight.k = d;

    std::vector<std::int32_t> ids(tokens);
    for (int t = 0; t < tokens; ++t) ids[t] = (t * 3 + 1) % kRows;
    GuardedDeviceBuffer device_ids(ids.size() * 4), output(static_cast<std::size_t>(d) * tokens * 2 + output_offset);
    device_ids.copy_from_host(ids.data(), device_ids.bytes());
    output.fill(0x7d);
    Tensor id_tensor(device_ids.span(), DType::I32, {tokens});
    Tensor out_tensor(output.span().subspan(output_offset), DType::BF16, {d, tokens});
    ops::embedding(id_tensor, weight, out_tensor, cuda_environment().default_execution);
    cuda_synchronize();

    std::vector<std::uint16_t> expected(static_cast<std::size_t>(d) * tokens);
    for (int t = 0; t < tokens; ++t)
        for (int k = 0; k < d; ++k)
            expected[static_cast<std::size_t>(t) * d + k] =
                norm_zero(kExpected[code_of(ids[t], k / kGroup, k % kGroup) + 128][scale_of(ids[t], k / kGroup)]);
    std::vector<std::uint8_t> raw(expected.size() * 2);
    output.copy_to_host(raw.data(), raw.size(), output_offset);
    std::vector<std::uint16_t> got(expected.size());
    for (std::size_t i = 0; i < got.size(); ++i) got[i] = norm_zero(static_cast<std::uint16_t>(raw[2 * i] | (raw[2 * i + 1] << 8)));

    const std::string label = "embedding q8 exact d=" + std::to_string(d) + " t=" + std::to_string(tokens) +
                              " offset=" + std::to_string(output_offset);
    int failures = verify_exact(label.c_str(), got, expected);
    failures += verify_exact((label + " preserves ids").c_str(), from_device<std::int32_t>(device_ids.data(), ids.size()), ids);
    std::vector<std::uint8_t> after(host.size());
    payload.copy_to_host(after.data(), after.size());
    failures += verify_exact((label + " preserves table").c_str(), after, host);
    failures += payload.verify_guards((label + " table").c_str()) + output.verify_guards((label + " output").c_str()) +
                device_ids.verify_guards((label + " ids").c_str());
    return failures;
}

